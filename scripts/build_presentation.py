"""Rebuild presentation/slides.pdf and keep its numbers in sync with the engine.

What it does (smallest practical pipeline, no new dependencies):

  1. Locate the LaTeX source at ``presentation/slides.tex``.
  2. Reproduce the *reference* backtest using the existing engine
     (``backtest.fetch_data`` + ``backtest.run_backtest``) -- the same code
     path the dashboard uses. No re-implementation of the model.
     Reference config: SPY Jan 2020 -- Dec 2025, $10,000 capital,
     target DTE 30, risk-free 1.0%, dividend yield 1.3%, one call + one put,
     Fixed DTE mode.
  3. Write ``presentation/generated/results.tex``: a small set of
     ``\\newcommand`` macros whose values come from the computed results.
  4. Check that every ``\\includegraphics`` target in ``slides.tex`` exists.
  5. If a LaTeX compiler is available, compile ``slides.tex`` into
     ``presentation/slides.pdf`` (verifying the page count) and replace the
     existing PDF. If it is NOT available -- or the compile fails -- print
     installation / build instructions and leave the existing PDF untouched.

Run it from anywhere:

    py -3.12 scripts/build_presentation.py

Exit codes: 0 = PDF (re)built; 2 = could not build (no LaTeX / compile
failure) but everything else succeeded and the prior PDF was preserved;
1 = a hard error (source missing, image missing, data fetch failed, ...).
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

# Make the project root (which holds backtest.py) importable no matter where
# this script is launched from.
ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import backtest as bt  # noqa: E402

PRES = ROOT / "presentation"
TEX = PRES / "slides.tex"
PDF = PRES / "slides.pdf"
GEN = PRES / "generated"
RESULTS = GEN / "results.tex"
BUILD = PRES / "_build"

# The reference configuration shown in the presentation. These are the
# dashboard defaults; they are the *inputs*, not the results.
REFERENCE = {
    "initial_capital": 10_000,
    "target_dte": 30,
    "risk_free": 0.01,
    "dividend_yield": 0.013,
}

EXPECTED_PAGES = 15  # the approved deck is 15 slides


def fail(msg: str, code: int = 1) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(code)


def note(msg: str) -> None:
    print(f"  {msg}")


# ---------------------------------------------------------------------------
# 2. Reproduce the reference backtest with the existing engine
# ---------------------------------------------------------------------------
def compute_results() -> dict:
    note("Fetching SPY + VIX data (yfinance) ...")
    data = bt.fetch_data()
    note(f"Running reference backtest "
         f"(capital={REFERENCE['initial_capital']:,}, "
         f"dte={REFERENCE['target_dte']}, "
         f"r={REFERENCE['risk_free'] * 100:.1f}%, "
         f"q={REFERENCE['dividend_yield'] * 100:.1f}%) ...")
    res = bt.run_backtest(
        data,
        initial_capital=REFERENCE["initial_capital"],
        target_dte=REFERENCE["target_dte"],
        risk_free=REFERENCE["risk_free"],
        dividend_yield=REFERENCE["dividend_yield"],
    )
    s = res["summary"]
    trades = res["trades"]
    wins = int(trades["win"].sum())
    losses = int(len(trades) - wins)
    return {
        "total_return": s["total_return"],
        "max_drawdown": s["max_drawdown"],
        "win_rate": s["win_rate"],
        "n_trades": s["n_trades"],
        "final_equity": s["final_equity"],
        # Sum of the *recorded* (per-trade, 2-dp) net P&L -- the value the
        # "results tell us" slide quotes. This can differ from
        # initial + (final_equity - initial) by a few cents because the
        # table rounds each trade to 2dp before summing.
        "net_pnl_sum": float(trades["net_pnl"].sum()),
        "wins": wins,
        "losses": losses,
        "initial_capital": s["initial_capital"],
    }


# ---------------------------------------------------------------------------
# 3. Write generated/results.tex from the computed values
# ---------------------------------------------------------------------------
def _pct(v: float, decimals: int) -> str:
    return f"{v * 100:.{decimals}f}\\%"


def _usd(v: float) -> str:
    """A dollar amount for text mode: ``\\$1,234.56`` -> ``\\$1{,}234.56``."""
    return f"\\${v:,.2f}".replace(",", "{,}")


def _signed_math_usd(v: float) -> str:
    """A signed dollar amount ready for ``$\\NetPnlSum$``: ``-$9{,}597.98``."""
    sign = "-" if v < 0 else "+"
    return f"{sign}\\${abs(v):,.2f}".replace(",", "{,}")


def write_results(v: dict) -> None:
    wr = v["win_rate"] * 100
    wr_str = f"{wr:.0f}\\%" if wr == int(wr) else f"{wr:.1f}\\%"
    lines = [
        "% Auto-generated by scripts/build_presentation.py -- DO NOT EDIT.",
        f"% Generated {date.today().isoformat()} from the backtest engine",
        f"%   (capital {v['initial_capital']:,.0f}, target DTE "
        f"{REFERENCE['target_dte']}, r {REFERENCE['risk_free'] * 100:.1f}%, "
        f"q {REFERENCE['dividend_yield'] * 100:.1f}%).",
        "% Referenced by presentation/slides.tex via \\input{generated/results}.",
        "\\newcommand{\\TotalReturn}{" + _pct(v["total_return"], 1) + "}",
        "\\newcommand{\\MaxDrawdown}{" + _pct(v["max_drawdown"], 1) + "}",
        "\\newcommand{\\WinRate}{" + wr_str + "}",
        "\\newcommand{\\TradeCount}{" + str(int(v["n_trades"])) + "}",
        "\\newcommand{\\FinalValue}{" + _usd(v["final_equity"]) + "}",
        "\\newcommand{\\NetPnlSum}{" + _signed_math_usd(v["net_pnl_sum"]) + "}",
        "\\newcommand{\\WinCount}{" + str(int(v["wins"])) + "}",
        "\\newcommand{\\LossCount}{" + str(int(v["losses"])) + "}",
        "",
    ]
    GEN.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text("\n".join(lines), encoding="utf-8")
    note(f"Wrote {RESULTS.relative_to(ROOT)}")


# ---------------------------------------------------------------------------
# 4. Every \\includegraphics target must exist
# ---------------------------------------------------------------------------
def check_images() -> list:
    tex = TEX.read_text(encoding="utf-8")
    refs = re.findall(
        r"\\includegraphics\s*(?:\[[^\]]*\])?\s*\{([^}]+)\}", tex)
    if not refs:
        fail("no \\includegraphics found in slides.tex (unexpected)")
    missing = []
    for ref in refs:
        direct = PRES / ref
        if direct.is_file():
            continue
        # Helpful hint: the approved deck used bare filenames; after the
        # reorganization the images live in presentation/figures/.
        if (PRES / "figures" / Path(ref).name).is_file():
            fail(f"{ref} is not next to slides.tex; it is in figures/ -- "
                 f"update the path to 'figures/{Path(ref).name}'")
        missing.append(ref)
    if missing:
        fail("missing image(s): " + ", ".join(missing))
    note(f"All {len(refs)} \\includegraphics target(s) present")
    return refs


# ---------------------------------------------------------------------------
# 5. Compile (only if a LaTeX toolchain is present)
# ---------------------------------------------------------------------------
def find_compiler():
    for exe in ("pdflatex", "latexmk", "xelatex", "lualatex"):
        path = shutil.which(exe)
        if path:
            return exe, path
    return None, None


def install_instructions() -> None:
    print()
    print("A LaTeX toolchain was not found, so slides.pdf could not be "
          "rebuilt.")
    print("The previously approved presentation/slides.pdf was left "
          "UNCHANGED.")
    print("Install one of the following, then re-run this script:")
    print()
    print("  Windows :  winget install MiKTeX.miktex")
    print("            (or the TeX Live ISO: https://tug.org/texlive/)")
    print("  macOS   :  brew install --cask mactex")
    print("            (or the lighter: brew install --cask basictex,")
    print("             then add /Library/TeX/texbin to PATH and run")
    print("             tlmgr install metropolis pgfplots tikz booktabs)")
    print("  Linux   :  sudo tlmgr install metropolis pgfplots  "
          "(TeX Live), or your distro's 'texlive-full' package.")
    print()
    print("Packages this deck needs: beamer + metropolis theme, "
          "pgfplots, tikz, booktabs, amsmath/amssymb.")
    print()
    print("After installing, rebuild with:")
    print(f"  {sys.executable} {Path(__file__).relative_to(ROOT)}")


def _pdf_pages_from_log(log: Path) -> int | None:
    if not log.is_file():
        return None
    m = re.search(r"Output written on .*?\((\d+) pages?",
                  log.read_text(encoding="utf-8", errors="ignore"))
    return int(m.group(1)) if m else None


def compile_pdf(exe: str) -> bool:
    """Compile in an isolated build dir; replace slides.pdf only on success.
    Returns True on a verified build, False otherwise (PDF left untouched).
    """
    try:
        shutil.rmtree(BUILD, ignore_errors=True)
        BUILD.mkdir(parents=True)
    except OSError as e:
        note(f"Could not prepare build dir ({e}); keeping existing PDF")
        return False

    # pdflatex (the approved deck was produced with pdfTeX); fall back to
    # latexmk -pdf if that is what is installed.
    if exe == "latexmk":
        cmd = ["latexmk", "-pdf", "-interaction=nonstopmode",
               "-halt-on-error", f"-output-directory={BUILD}", TEX.name]
    else:
        cmd = [exe, "-interaction=nonstopmode", "-halt-on-error",
               f"-output-directory={BUILD}", TEX.name]

    # Beamer is not order-sensitive for page count, but two passes settle
    # any link/page-reference aux state.
    ok = True
    for _ in range(2):
        r = subprocess.run(cmd, cwd=PRES, capture_output=True, text=True)
        if r.returncode != 0:
            ok = False
            break
    out_pdf = BUILD / "slides.pdf"
    pages = _pdf_pages_from_log(BUILD / "slides.log")

    if not ok or not out_pdf.is_file():
        note("Compilation failed -- keeping the existing slides.pdf.")
        log = BUILD / "slides.log"
        if log.is_file():
            tail = log.read_text(encoding="utf-8", errors="ignore").splitlines()
            for ln in tail[-40:]:
                print("    " + ln)
        return False

    if pages is not None and pages != EXPECTED_PAGES:
        note(f"Compiled, but got {pages} pages (expected {EXPECTED_PAGES}) "
             f"-- keeping the existing slides.pdf.")
        return False

    # Verified: move the fresh PDF over the approved one.
    shutil.copyfile(out_pdf, PDF)
    note(f"Rebuilt {PDF.relative_to(ROOT)} ({pages if pages is not None else '?'} pages)")
    return True


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
def main() -> None:
    print("=== build_presentation.py ===")
    if not TEX.is_file():
        fail(f"source not found: {TEX}")
    note(f"Source: {TEX.relative_to(ROOT)}")

    # 2+3: reproduce the reference config, then emit the generated values.
    values = compute_results()
    write_results(values)

    # Echo the generated numbers so the build log is self-documenting.
    note("Generated values:")
    note(f"  Total Return      {_pct(values['total_return'], 1)}")
    note(f"  Max Drawdown      {_pct(values['max_drawdown'], 1)}")
    note(f"  Win Rate          {values['win_rate'] * 100:.0f}\\%")
    note(f"  Trades            {int(values['n_trades'])}")
    note(f"  Final Value       {_usd(values['final_equity'])}")
    note(f"  Net P&L Sum       {_signed_math_usd(values['net_pnl_sum'])}")
    note(f"  Wins / Losses     "
         f"{int(values['wins'])} / {int(values['losses'])}")

    # 4: image presence.
    check_images()

    # 5: compile (best-effort; never deletes the existing PDF).
    exe, path = find_compiler()
    print()
    if exe is None:
        install_instructions()
        sys.exit(2)
    print(f"  Found {exe} at {path}")
    if compile_pdf(exe):
        print("=== OK: slides.pdf rebuilt ===")
        sys.exit(0)
    else:
        print("=== BUILD FAILED: existing slides.pdf preserved ===")
        sys.exit(2)


if __name__ == "__main__":
    main()
